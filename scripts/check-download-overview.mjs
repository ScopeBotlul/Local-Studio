import {build} from 'vite';
import {chromium,expect} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
await build({configFile:false,define:{'process.env.NODE_ENV':JSON.stringify('production')},build:{outDir:'.artifacts/download-overview-fixture',emptyOutDir:false,lib:{entry:'scripts/download-overview-fixture.jsx',name:'DownloadFixture',formats:['iife'],fileName:()=> 'fixture.js'}}});
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.setContent('<!doctype html><html lang="de"><body><div id="root"></div></body></html>');
 await page.addStyleTag({path:'.artifacts/download-overview-fixture/local-studio.css'});
 await page.addScriptTag({path:'.artifacts/download-overview-fixture/fixture.js'});
 await page.clock.install();await page.evaluate(()=>window.DownloadFixture.mount());
 const button=page.getByRole('button',{name:'Laufende Downloads',exact:true});
 await button.click();const dialog=page.getByRole('dialog');
 await expect(dialog).toBeVisible();await expect(dialog.getByRole('progressbar')).toHaveCount(2);
 await expect(dialog).toContainText('Noch ca. 2 Min.');await expect(dialog).not.toContainText('test/finished');
 await expect(dialog).toContainText('Wartet auf Start');
 await page.evaluate(()=>{window.downloadFixture.rows[0].status='verifying';window.downloadFixture.rows[1].status='completed';});
 await page.clock.runFor(1100);await expect(dialog.getByRole('progressbar')).toHaveCount(1);
 await expect(dialog).toContainText('Dateien werden geprüft');await expect(dialog).not.toContainText('Noch ca.');
 await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();await expect(button).toBeFocused();
 const calls=await page.evaluate(()=>window.downloadFixture.calls);await page.clock.runFor(3000);
 expect(await page.evaluate(()=>window.downloadFixture.calls)).toBe(calls);
 await button.click();await expect(dialog).toBeVisible();
 await page.getByRole('button',{name:'Alle Downloads',exact:true}).click();
 expect(await page.evaluate(()=>window.downloadFixture.opened)).toBe(1);await expect(dialog).not.toBeVisible();
 await page.evaluate(()=>{window.downloadFixture.rows=[];document.documentElement.style.setProperty('--ui-scale','1.5');});
 await button.click();await expect(dialog).toContainText('Keine laufenden Downloads.');
 const bounds=await dialog.boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.y).toBeGreaterThanOrEqual(36);expect(bounds.width).toBeLessThan(450);
 await page.evaluate(()=>{window.downloadFixture.fail=true;});await page.clock.runFor(1100);await expect(dialog).toContainText('nicht erreichbar');
 await page.mouse.click(900,500);await expect(dialog).not.toBeVisible();
 await page.evaluate(()=>{window.downloadFixture.fail=false;window.downloadFixture.update={phase:'downloading',received:100,total:10000,latest:{version:'99.0.0'}};});
 await button.click();await expect(dialog).toContainText('Local Studio 99.0.0');await expect(dialog).toContainText('Restzeit wird ermittelt');
 await page.evaluate(()=>{window.downloadFixture.update.received=200;});await page.clock.runFor(1100);
 await expect(dialog).toContainText('Noch ca.');
 await page.evaluate(()=>{window.downloadFixture.update.phase='ready';});await page.clock.runFor(1100);
 await expect(dialog).toContainText('Keine laufenden Downloads.');
 await button.click();await expect(dialog).not.toBeVisible();
 expect(errors).toEqual([]);
 await writeFile('.artifacts/download-overview-browser.json',JSON.stringify({passed:true,scope:'Headless Edge, real WindowFrame/React dialogs with mocked download IPC; active filtering, ETA, polling, completion, Escape/focus, navigation, empty/error states, 150% zoom, outside click. No real network downloads.'},null,2));
 console.log('PASS download overview browser checks');
} finally {await browser.close();}
